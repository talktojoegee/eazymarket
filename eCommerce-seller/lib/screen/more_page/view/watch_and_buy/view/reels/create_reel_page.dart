class CreateReelPage extends StatefulWidget {
  final int? reelId;
  final int? profileId;

  const CreateReelPage({
    super.key,
    this.reelId,
    this.profileId,
  });

  @override
  State<CreateReelPage> createState() => _CreateReelPageState();
}

class _CreateReelPageState extends State<CreateReelPage> {
  final _formKey = GlobalKey<FormState>();
  late final TextEditingController _captionController;
  final WatchAndBuyRepo _repo = WatchAndBuyRepo();

  File? _videoFile;
  File? _coverFile;
  bool _videoRemoved = false;
  bool _coverRemoved = false;
  bool _isAutoGeneratedFrame = false;
  bool _isExtractingFrame = false;
  bool _isFetchingReel = false;
  WatchAndBuyReelModel? _fetchedReel;
  EligibleProductModel? _primaryProduct;
  List<EligibleProductModel> _selectedProducts = [];

  bool _isLoading = false;

  WatchAndBuyReelModel? get _currentReel => _fetchedReel;

  bool get isEditing => widget.reelId != null;

  bool get _hasVideo =>
      (_videoFile != null || (_currentReel?.videoUrl != null && _currentReel!.videoUrl!.isNotEmpty)) &&
      !_videoRemoved;

  bool get _hasCover =>
      (_coverFile != null || (_currentReel?.coverUrl != null && _currentReel!.coverUrl!.isNotEmpty)) &&
      !_coverRemoved;

  @override
  void initState() {
    super.initState();
    _captionController = TextEditingController();
    _captionController.addListener(() {
      if (mounted) setState(() {});
    });

    if (widget.reelId != null) {
      _isFetchingReel = true;
      _fetchSingleReel(widget.reelId!);
    }
  }

  void _populateFromReel(WatchAndBuyReelModel reel) {
    _captionController.text = reel.caption ?? '';
    _selectedProducts = List.from(reel.products);
    if (reel.primaryAttachmentId != null && _selectedProducts.isNotEmpty) {
      _primaryProduct = _selectedProducts.firstWhere(
        (p) => p.attachmentId == reel.primaryAttachmentId ||
               p.id == reel.primaryAttachmentId ||
               p.productId == reel.primaryAttachmentId ||
               p.variantId == reel.primaryAttachmentId,
        orElse: () => _selectedProducts.firstWhere(
          (p) => p.isPrimary,
          orElse: () => _selectedProducts.first,
        ),
      );
    } else if (_selectedProducts.isNotEmpty) {
      _primaryProduct = _selectedProducts.firstWhere(
        (p) => p.isPrimary,
        orElse: () => _selectedProducts.first,
      );
    } else {
      _primaryProduct = null;
    }
  }

  Future<void> _fetchSingleReel(int reelId) async {
    setState(() {
      _isFetchingReel = true;
    });

    try {
      final freshReel = await _repo.getSingleReel(reelId);
      if (mounted) {
        setState(() {
          _fetchedReel = freshReel;
          _populateFromReel(freshReel);
        });
      }
    } catch (e) {
      debugPrint('Error fetching single reel: $e');
      if (mounted) {
        showCustomSnackbar(
          context: context,
          message: 'Failed to load reel: ${e.toString().replaceAll('Exception:', '').trim()}',
          isError: true,
        );
      }
    } finally {
      if (mounted) {
        setState(() {
          _isFetchingReel = false;
        });
      }
    }
  }

  @override
  void dispose() {
    _captionController.dispose();
    super.dispose();
  }

  void _removeVideo() {
    setState(() {
      _videoFile = null;
      _videoRemoved = true;
    });
  }

  void _removeCover() {
    setState(() {
      _coverFile = null;
      _coverRemoved = true;
      _isAutoGeneratedFrame = false;
    });
  }

  Future<void> _extractFrameFromVideo([String? videoPath]) async {
    if (_isExtractingFrame) return;

    setState(() {
      _isExtractingFrame = true;
    });

    String? localPath = videoPath ?? _videoFile?.path;

    // If local file is null (e.g. edit mode with remote videoUrl), download video to temp file
    if ((localPath == null || localPath.isEmpty) &&
        _currentReel?.videoUrl != null &&
        _currentReel!.videoUrl!.isNotEmpty) {
      try {
        final tempDir = await getTemporaryDirectory();
        final tempVideoPath = '${tempDir.path}/temp_reel_video_${DateTime.now().millisecondsSinceEpoch}.mp4';
        final dio = Dio();
        await dio.download(_currentReel!.videoUrl!, tempVideoPath);
        if (File(tempVideoPath).existsSync()) {
          localPath = tempVideoPath;
        }
      } catch (e) {
        debugPrint('Error downloading remote video for frame extraction: $e');
      }
    }

    if (localPath == null || localPath.isEmpty || !File(localPath).existsSync()) {
      setState(() {
        _isExtractingFrame = false;
      });
      if (mounted) {
        showCustomSnackbar(
          context: context,
          message: 'Please upload or select a video first to extract a frame',
          isError: true,
        );
      }
      return;
    }

    try {
      final thumbnailFile = await VideoCompress.getFileThumbnail(
        localPath,
        quality: 85,
        position: 100, // 100ms into video for a clean frame
      );

      if (thumbnailFile.existsSync()) {
        setState(() {
          _coverFile = thumbnailFile;
          _coverRemoved = false;
          _isAutoGeneratedFrame = true;
        });
        if (mounted) {
          showCustomSnackbar(
            context: context,
            message: 'Video frame extracted as cover image',
          );
        }
      } else {
        if (mounted) {
          showCustomSnackbar(
            context: context,
            message: 'Could not generate thumbnail from video',
            isError: true,
          );
        }
      }
    } catch (e) {
      debugPrint('Error generating video frame thumbnail: $e');
      if (mounted) {
        showCustomSnackbar(
          context: context,
          message: 'Failed to extract frame: ${e.toString().replaceAll('Exception:', '').trim()}',
          isError: true,
        );
      }
    } finally {
      if (mounted) {
        setState(() {
          _isExtractingFrame = false;
        });
      }
    }
  }

  Future<void> _pickVideo() async {
    final settings = HiveStorage.watchAndBuySettings;
    final maxDurationSec =
        settings.maxDurationSeconds > 0 ? settings.maxDurationSeconds : 60;
    final maxUploadMb =
        settings.maxUploadMb > 0 ? settings.maxUploadMb.toDouble() : 10.0;

    final path = await ImagePickerUtils.pickMedia(
      context,
      mediaType: MediaType.video,
      maxSizeMb: maxUploadMb,
      maxVideoDuration: Duration(seconds: maxDurationSec),
    );
    if (path != null) {
      setState(() {
        _videoFile = File(path);
        _videoRemoved = false;
      });

      // Auto-extract video frame image if no custom cover was chosen yet
      if (_coverFile == null && (_currentReel?.coverUrl == null || _coverRemoved)) {
        await _extractFrameFromVideo(path);
      }
    }
  }

  Future<void> _pickCover() async {
    final settings = HiveStorage.watchAndBuySettings;
    final path = await ImagePickerUtils.pickMedia(
      context,
      mediaType: MediaType.image,
      maxSizeMb: settings.maxUploadMb.toDouble(),
    );
    if (path != null) {
      setState(() {
        _coverFile = File(path);
        _coverRemoved = false;
        _isAutoGeneratedFrame = false;
      });
    }
  }

  Future<void> _openProductSelector() async {
    final settings = HiveStorage.watchAndBuySettings;
    final result = await EligibleProductsSheet.show(
      context,
      maxSelections: settings.maxProductsPerReel,
      requirePrimary: true,
      initialPrimary: _primaryProduct,
      initialSelections: _selectedProducts,
    );

    if (result != null) {
      setState(() {
        _primaryProduct = result.primaryProduct;
        _selectedProducts = result.selectedProducts;
      });
    }
  }

  Future<void> _submit() async {
    if (!_formKey.currentState!.validate()) return;

    if (!isEditing && !_hasVideo) {
      showCustomSnackbar(context: context, message: 'Please select a reel video', isError: true);
      return;
    }

    if (!_hasCover) {
      showCustomSnackbar(
        context: context,
        message: 'Please select or extract a cover image for the reel',
        isError: true,
      );
      return;
    }

    if (_primaryProduct == null || _selectedProducts.isEmpty) {
      showCustomSnackbar(
        context: context,
        message: 'Please tag at least 1 product and select a primary product',
        isError: true,
      );
      return;
    }

    final settings = HiveStorage.watchAndBuySettings;
    final maxUploadMb =
        settings.maxUploadMb > 0 ? settings.maxUploadMb.toDouble() : 10.0;

    if (_videoFile != null && _videoFile!.existsSync()) {
      final videoMb = _videoFile!.lengthSync() / (1024.0 * 1024.0);
      if (videoMb > maxUploadMb) {
        showCustomSnackbar(
          context: context,
          message:
              'Video size (${videoMb.toStringAsFixed(1)} MB) exceeds maximum allowed limit of ${maxUploadMb.toStringAsFixed(0)} MB',
          isError: true,
        );
        return;
      }
    }

    setState(() {
      _isLoading = true;
    });

    try {
      final List<int> attachmentIds = [];
      for (final p in _selectedProducts) {
        final attId = p.attachmentId;
        if (attId > 0 && !attachmentIds.contains(attId)) {
          attachmentIds.add(attId);
        }
      }

      final primaryId = _primaryProduct?.attachmentId ?? (attachmentIds.isNotEmpty ? attachmentIds.first : 0);

      if (primaryId > 0 && !attachmentIds.contains(primaryId)) {
        attachmentIds.insert(0, primaryId);
      }

      if (isEditing) {
        final reelIdToUpdate = _currentReel?.id ?? widget.reelId!;
        await _repo.updateReel(
          reelId: reelIdToUpdate,
          caption: _captionController.text.trim(),
          source: 'seller',
          profileId: widget.profileId,
          video: _videoFile,
          cover: _coverFile,
          primaryAttachmentId: primaryId,
          attachmentIds: attachmentIds,
        );
        if (mounted) {
          showCustomSnackbar(context: context, message: 'Reel updated successfully');
          Navigator.pop(context, true);
        }
      } else {
        await _repo.createReel(
          caption: _captionController.text.trim(),
          source: 'seller',
          profileId: widget.profileId,
          video: _videoFile,
          cover: _coverFile,
          primaryAttachmentId: primaryId,
          attachmentIds: attachmentIds,
        );
        if (mounted) {
          showCustomSnackbar(context: context, message: 'Reel created successfully');
          Navigator.pop(context, true);
        }
      }
    } catch (e) {
      if (mounted) {
        showCustomSnackbar(
          context: context,
          message: e.toString().replaceAll('Exception:', '').trim(),
          isError: true,
        );
      }
    } finally {
      if (mounted) {
        setState(() {
          _isLoading = false;
        });
      }
    }
  }

