                  children: [
                    Row(
                      children: [
                        if (isPrimary)
                          Container(
                            padding: const EdgeInsets.symmetric(horizontal: 6, vertical: 2),
                            margin: const EdgeInsets.only(right: 6),
                            decoration: BoxDecoration(
                              color: const Color(0xFFFBF4E4),
                              borderRadius: BorderRadius.circular(6),
                            ),
                            child: const Text(
                              'PRIMARY',
                              style: TextStyle(
                                fontSize: 9,
                                fontWeight: FontWeight.w800,
                                color: Color(0xFF8C6B1F),
                                letterSpacing: 0.4,
                              ),
                            ),
                          ),
                        Expanded(
                          child: Text(
                            item.productTitle,
                            maxLines: 1,
                            overflow: TextOverflow.ellipsis,
                            style: TextStyle(
                              fontWeight: FontWeight.w600,
                              fontSize: 13.5,
                              color: isDark ? Colors.white : const Color(0xFF1F2024),
                            ),
                          ),
                        ),
                      ],
                    ),
                    const SizedBox(height: 2),
                    Text(
                      item.variantTitle != null && item.variantTitle!.isNotEmpty
                          ? item.variantTitle!
                          : item.formattedPrice,
                      style: TextStyle(
                        fontSize: 12,
                        color: isDark ? Colors.white54 : const Color(0xFF8E8E93),
                      ),
                    ),
                  ],
                ),
              ),

              // Set Primary option if not already primary
              if (!isPrimary)
                InkWell(
                  onTap: () {
                    setState(() {
                      _primaryProduct = item;
                    });
                  },
                  borderRadius: BorderRadius.circular(4),
                  child: const Padding(
                    padding: EdgeInsets.symmetric(horizontal: 6, vertical: 4),
                    child: Text(
                      'Set Primary',
                      style: TextStyle(fontSize: 11, color: AppColors.primaryColor, fontWeight: FontWeight.bold),
                    ),
                  ),
                ),

              // Remove Tag close button
              IconButton(
                icon: Icon(Icons.close, size: 16, color: isDark ? Colors.white54 : const Color(0xFF8E8E93)),
                onPressed: () {
                  setState(() {
                    _selectedProducts.removeAt(index);
                    if (_primaryProduct != null &&
                        (_primaryProduct!.uniqueKey == item.uniqueKey || _primaryProduct == item)) {
                      _primaryProduct = _selectedProducts.isNotEmpty ? _selectedProducts.first : null;
                    }
                  });
                },
              ),
            ],
          ),
        );
      },
    );
  }

